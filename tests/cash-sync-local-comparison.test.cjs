'use strict';
const assert=require('node:assert/strict');
const original=globalThis.XLSX;
globalThis.XLSX={utils:{sheet_to_json:s=>s.rows}};
const audit=require('../site/assets/js/cash-sync-historical-audit.js');
const {importRows}=require('../site/assets/js/cash-sync-local-comparison.js');
const header=['Ngày','Tên công ty','Số hợp đồng','Nội dung','IPC','Loại','Thu','Thầu phụ','Vật tư','CP trực tiếp khác','CP gián tiếp','CP tài chính','Phải trả khác','Số dư'];
const rows=[header,['2026-10-01','','','','','',100,0,0,0,0,0,0,100]];
const book={SheetNames:['ELYSIAN'],Sheets:{ELYSIAN:{rows}}};
const imported=importRows(book,'ELYSIAN',audit);
assert.equal(imported.length,1);
assert.equal(imported[0].income,100);
assert.equal(imported[0].date,'2026-10-01');
const report=audit.compareLoadedCashControl(rows,'ELYSIAN',imported,{sourceComplete:false});
assert.equal(report.sourceComplete,false);
assert.equal(report.canWrite,false);
assert.equal(report.matched,1);
assert.throws(()=>importRows(book,'EATON',audit),/sheet mang tên dự án/);
assert.throws(()=>importRows({SheetNames:['ELYSIAN'],Sheets:{ELYSIAN:{rows:[['Date','X']]}}},'ELYSIAN',audit),/A:N/);
globalThis.XLSX=original;
console.log('local comparison guard tests passed');
